<?php

declare(strict_types=1);

namespace TowerDNS\Infrastructure\Console;

use Devium\Toml\Toml;
use Doctrine\DBAL\DriverManager;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Input\InputOption;
use Symfony\Component\Console\Output\OutputInterface;
use TowerDNS\Infrastructure\Installation\DocumentRootPolicy;
use TowerDNS\Infrastructure\Ui\AssetManifest;

/** Read-only preflight for a fresh installation; database connection is optional until configured. */
#[AsCommand(name: 'towerdns:install:check', description: 'Check prerequisites for a fresh TowerDNS installation')]
final class InstallCheckCommand extends Command
{
    public function __construct(private readonly string $projectRoot)
    {
        parent::__construct();
    }

    #[\Override]
    protected function configure(): void
    {
        $this->addOption('format', null, InputOption::VALUE_REQUIRED, 'Output format: table or json', 'table', ['table', 'json']);
    }

    #[\Override]
    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $checks = [];
        $add    = static function (string $name, string $status, string $detail) use (&$checks): void {
            $checks[] = ['check' => $name, 'status' => $status, 'detail' => $detail];
        };
        $add('php', PHP_VERSION_ID >= 80403 ? 'PASS' : 'FAIL', PHP_VERSION_ID >= 80403 ? PHP_VERSION : 'PHP 8.4.3 or newer is required');
        foreach (['pdo', 'openssl', 'sodium', 'intl', 'mbstring', 'json'] as $extension) {
            $add('extension.' . $extension, extension_loaded($extension) ? 'PASS' : 'FAIL', extension_loaded($extension) ? 'loaded' : 'install/enable the PHP extension');
        }
        foreach (['pdo_sqlite', 'pdo_mysql', 'pdo_pgsql'] as $extension) {
            $add('database_driver.' . $extension, extension_loaded($extension) ? 'PASS' : 'WARN', extension_loaded($extension) ? 'available' : 'optional unless this database is selected');
        }
        $add('composer_autoload', is_file($this->projectRoot . '/vendor/autoload.php') ? 'PASS' : 'FAIL', 'run composer install --no-dev');
        $add('composer_lock', is_file($this->projectRoot . '/composer.lock') ? 'PASS' : 'FAIL', 'composer.lock is required for reproducible deployment');
        $add('composer_platform_check', is_file($this->projectRoot . '/vendor/composer/platform_check.php') ? 'PASS' : 'WARN', 'install production dependencies from composer.lock on the target PHP runtime');
        $add('runtime_fpm', 'WARN', 'this command checks only its current PHP SAPI; run it through the deployed PHP-FPM runtime to compare extensions and PHP version');
        foreach (['data', 'logs', 'cache/ratelimit', 'configs'] as $relative) {
            $path = $this->projectRoot . '/' . $relative;
            $add('path.' . $relative, is_dir($path) && is_writable($path) ? 'PASS' : 'WARN', 'create this private runtime directory and grant write access to the TowerDNS PHP user');
        }

        $appConfig       = $this->readToml($this->projectRoot . '/configs/config.local.toml');
        $dbConfig        = $this->readToml($this->projectRoot . '/configs/database.toml');
        $appConfigExists = is_file($this->projectRoot . '/configs/config.local.toml');
        $add('config.application', $appConfig === null ? ($appConfigExists ? 'FAIL' : 'WARN') : 'PASS', $appConfig === null ? ($appConfigExists ? 'file is unreadable or invalid TOML' : 'not configured yet; the explicit installer creates it') : 'valid TOML configuration');
        $keyValue   = $appConfig['security']['encryption_key'] ?? null;
        $decodedKey = is_string($keyValue) ? base64_decode($keyValue, true) : false;
        $keyValid   = is_string($decodedKey) && strlen($decodedKey) === 32;
        $add('application_key', $appConfig === null ? ($appConfigExists ? 'FAIL' : 'WARN') : ($keyValid ? 'PASS' : 'FAIL'), $appConfig === null ? ($appConfigExists ? 'cannot verify key because configuration is invalid' : 'will be generated by the explicit installer; value is never displayed') : ($keyValid ? 'configured; secret value is never displayed' : 'missing or invalid 32-byte base64 key'));

        $domain     = $appConfig['app']['domain']      ?? null;
        $forceHttps = $appConfig['app']['force_https'] ?? null;
        if ($appConfig === null && !$appConfigExists) {
            $add('webauthn_origin', 'WARN', 'configure a public HTTPS hostname before enrolling the first administrator');
        } elseif ($appConfig === null) {
            $add('webauthn_origin', 'FAIL', 'application configuration is unreadable or invalid TOML');
        } elseif (!is_string($domain) || filter_var($domain, FILTER_VALIDATE_DOMAIN, FILTER_FLAG_HOSTNAME) === false) {
            $add('webauthn_origin', 'FAIL', 'app.domain must be a valid hostname for the WebAuthn RP ID');
        } elseif ($forceHttps !== true) {
            $add('webauthn_origin', 'WARN', 'hostname is valid, but WebAuthn requires HTTPS in the deployed browser origin');
        } else {
            $add('webauthn_origin', 'PASS', 'RP hostname is valid and HTTPS is enabled; verify the reverse-proxy origin matches');
        }
        $timezone = date_default_timezone_get();
        $add('timezone', in_array($timezone, timezone_identifiers_list(), true) ? 'PASS' : 'WARN', $timezone);

        $this->checkDatabase($dbConfig, $add);

        try {
            new AssetManifest($this->projectRoot)->verifyComplete();
            $add('frontend_assets', 'PASS', 'activated production manifest and assets are complete');
        } catch (\Throwable) {
            $add('frontend_assets', 'FAIL', 'build and activate production assets before deployment');
        }
        $docroot = $_SERVER['DOCUMENT_ROOT'] ?? null;
        $matches = DocumentRootPolicy::matches($this->projectRoot, is_string($docroot) ? $docroot : null);
        $add('document_root', $matches ? 'PASS' : 'WARN', $matches ? 'httpdocs is the active document root' : 'configure the web server document root to the project httpdocs directory');
        $failures = count(array_filter($checks, static fn(array $check): bool => $check['status'] === 'FAIL'));
        $warnings = count(array_filter($checks, static fn(array $check): bool => $check['status'] === 'WARN'));
        if ((string) $input->getOption('format') === 'json') {
            $output->writeln(json_encode(['ready' => $failures === 0, 'summary' => ['pass' => count(array_filter($checks, static fn(array $check): bool => $check['status'] === 'PASS')), 'warn' => $warnings, 'fail' => $failures, 'skip' => count(array_filter($checks, static fn(array $check): bool => $check['status'] === 'SKIP'))], 'checks' => $checks], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR));
        } else {
            foreach ($checks as $check) {
                $output->writeln(sprintf('%s  %s: %s', $check['status'], $check['check'], $check['detail']));
            }
        }

        return $failures === 0 ? Command::SUCCESS : Command::FAILURE;
    }

    /** @param array<string, mixed>|null $config
     * @param callable(string, string, string): void $add
     */
    private function checkDatabase(?array $config, callable $add): void
    {
        if ($config === null) {
            $configured = is_file($this->projectRoot . '/configs/database.toml');
            $add('database_configuration', $configured ? 'FAIL' : 'WARN', $configured ? 'database.toml is unreadable or invalid TOML' : 'not configured yet; choose a database during explicit installation');
            $add('database_connection', 'SKIP', $configured ? 'invalid database configuration' : 'no configured database was contacted');
            return;
        }

        $database = $config['database'] ?? null;
        if (!is_array($database)) {
            $add('database_configuration', 'FAIL', 'database.toml is missing its [database] table');
            $add('database_connection', 'SKIP', 'invalid database configuration');
            return;
        }
        $driver = $database['driver'] ?? null;
        if (!is_string($driver) || !in_array($driver, ['pdo_sqlite', 'pdo_mysql', 'pdo_pgsql'], true)) {
            $add('database_configuration', 'FAIL', 'database.toml has a missing or unsupported driver');
            $add('database_connection', 'SKIP', 'invalid database configuration');
            return;
        }

        if (!extension_loaded($driver)) {
            $add('database_configuration', 'FAIL', 'the configured PDO driver is not loaded');
            $add('database_connection', 'SKIP', 'configured database driver is unavailable');
            return;
        }

        if ($driver === 'pdo_sqlite') {
            $sqlite = $database['sqlite'] ?? null;
            $path   = is_array($sqlite) ? ($sqlite['path'] ?? null) : null;
            if (!is_string($path) || $path === '') {
                $add('database_configuration', 'WARN', 'SQLite file does not exist yet; the explicit installer may create it');
                $add('database_connection', 'SKIP', 'preflight does not create or initialize SQLite files');
                return;
            }
            if (!is_file($path)) {
                $add('database_configuration', 'WARN', 'SQLite file does not exist yet; the explicit installer may create it');
                $add('database_connection', 'SKIP', 'preflight does not create or initialize SQLite files');
                return;
            }
            $params = ['driver' => $driver, 'path' => $path];
        } else {
            $host     = $database['host']     ?? null;
            $name     = $database['name']     ?? null;
            $user     = $database['user']     ?? null;
            $password = $database['password'] ?? '';
            $port     = $database['port']     ?? ($driver === 'pdo_pgsql' ? 5432 : 3306);
            if (!is_string($host) || $host === '' || !is_string($name) || $name === '' || !is_string($user) || $user === '' || !is_string($password) || !is_int($port) || $port < 1 || $port > 65535) {
                $add('database_configuration', 'FAIL', 'database.toml must contain a valid host, port, database name and user');
                $add('database_connection', 'SKIP', 'incomplete database configuration');
                return;
            }
            $params = [
                'driver'   => $driver, 'host' => $host, 'port' => $port, 'dbname' => $name, 'user' => $user,
                'password' => $password, 'driverOptions' => [\PDO::ATTR_TIMEOUT => 5],
            ];
            if ($driver === 'pdo_mysql') {
                $charset = $database['charset'] ?? 'utf8mb4';
                if (!is_string($charset) || $charset === '') {
                    $add('database_configuration', 'FAIL', 'database.toml contains an invalid charset');
                    $add('database_connection', 'SKIP', 'invalid database configuration');
                    return;
                }
                $params['charset'] = $charset;
            }
        }

        $add('database_configuration', 'PASS', $driver . ' selected; credentials are not displayed');
        $connection = null;
        try {
            $connection = DriverManager::getConnection($params);
            $connection->executeQuery('SELECT 1')->free();
            $versionQuery = match ($driver) {
                'pdo_sqlite' => 'SELECT sqlite_version()',
                'pdo_pgsql'  => 'SHOW server_version',
                default      => 'SELECT VERSION()',
            };
            $version = (string) $connection->fetchOne($versionQuery);
            $add('database_connection', 'PASS', 'connection and read-only version query succeeded (' . preg_replace('/[^0-9A-Za-z._ -]/', '', $version) . ')');
            $tables = $connection->createSchemaManager()->introspectTableNames();
            $add('database_state', $tables === [] ? 'PASS' : 'WARN', $tables === [] ? 'no application tables found' : 'database is not empty; review it before using the fresh installer or follow the upgrade procedure');
        } catch (\Throwable) {
            $add('database_connection', 'FAIL', 'connection failed; verify the selected database, network access and credentials (values are not displayed)');
        } finally {
            $connection?->close();
        }
    }

    /** @return array<string, mixed>|null */
    private function readToml(string $path): ?array
    {
        if (!is_file($path) || !is_readable($path)) {
            return null;
        }
        try {
            $decoded = Toml::decode((string) file_get_contents($path), asArray: true);
            return is_array($decoded) ? $decoded : null;
        } catch (\Throwable) {
            return null;
        }
    }
}
